"""Rewrite a Phase 0 step script (or lib.sh) for the Spark's local runner (ops/spark/run.sh).

The VM paths are remapped to folders under the Spark root on the host side only: in `-v HOST:CONTAINER` the
container side is kept, and `-e NAME=VALUE` is left alone, so every container sees the same paths as on the L4
(the harness reads /etc/vlar/image-digests.json, the images hold /opt/vla-router). `source .../lib.sh` points at the
rewritten lib.sh. The scripts themselves are not changed in the repo.

    python transform.py IN OUT      (environment: VLAR_SPARK_ROOT, VLAR_SPARK_REPO, VLAR_SPARK_RUN)
"""
import os
import re
import sys

SD, REPO, RUN = (os.environ[k] for k in ("VLAR_SPARK_ROOT", "VLAR_SPARK_REPO", "VLAR_SPARK_RUN"))
MAP = [(r"/opt/vla-router", REPO), (r"/etc/vlar(?!-)", f"{SD}/etc"), (r"/opt/weights", f"{SD}/weights"),
       (r"/opt/hf", f"{SD}/hf"), (r"/var/lib/vlar", f"{SD}/var")]
PROTECT = re.compile(r'(-v\s+"?)([^\s":]+)(:[^\s"]*"?)|-[ew]\s+\S+')
SOURCE = re.compile(r"source\s+/opt/vla-router/ops/vm/phase0/lib\.sh")


def host(text: str) -> str:
    for pat, new in MAP:
        text = re.sub(pat + r"(?=[/\s\"':}).;|]|$)", new, text)
    return text


def line(s: str) -> str:
    s = SOURCE.sub(f"source {RUN}/lib.sh", s)
    out, pos = [], 0
    for m in PROTECT.finditer(s):
        out.append(host(s[pos:m.start()]))
        out.append(m.group(1) + host(m.group(2)) + m.group(3) if m.group(1) else m.group(0))
        pos = m.end()
    out.append(host(s[pos:]))
    return "".join(out)


if __name__ == "__main__":
    src, dst = sys.argv[1:3]
    text = "".join(line(s) for s in open(src).read().splitlines(keepends=True))
    open(dst, "w").write(f"# generated by ops/spark/transform.py from {src}\n" + text)
