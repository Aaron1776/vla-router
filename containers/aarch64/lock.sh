#!/usr/bin/env bash
# The aarch64 (DGX Spark) variant of containers/lock.sh: the same inputs (containers/*.in), cutoff and index, resolved
# for linux/aarch64 (manylinux_2_28), CPython 3.13, with hashes. Writes containers/aarch64/{lerobot,xvla,build}.lock,
# the two test-only locks and lerobot.sdists. The x86_64 locks and containers/lock.sh are not touched.
# PyPI's torch 2.11.0 linux/aarch64 wheel is a CUDA 13.0 build too (its cuda-toolkit 13.0.2 dependency).
set -euo pipefail
cd "$(dirname "$0")"
UV="${UV:-uv}"
PY="${PY:-python3}"
IN=..
CUTOFF="2026-11-07T00:00:00Z"
PLAT=aarch64-manylinux_2_28
for env in lerobot xvla build; do
  "$UV" pip compile "$IN/$env.in" -o "$env.lock" --generate-hashes --emit-index-url \
    --python-version 3.13 --python-platform "$PLAT" --index-url https://pypi.org/simple \
    --exclude-newer "$CUTOFF" --no-header --quiet
  { echo "# $env.lock: generated by containers/aarch64/lock.sh from ../$env.in (uv $("$UV" --version | awk '{print $2}'))"
    echo "# target: linux/aarch64 (manylinux_2_28), CPython 3.13; exclude-newer $CUTOFF"
    cat "$env.lock"; } > "$env.lock.tmp" && mv "$env.lock.tmp" "$env.lock"
done
for env in xvla lerobot; do
  "$UV" pip compile "$IN/$env-test.in" -c "$env.lock" -o "$env-test.full" --generate-hashes --emit-index-url \
    --python-version 3.13 --python-platform "$PLAT" --index-url https://pypi.org/simple \
    --exclude-newer "$CUTOFF" --no-header --quiet
  { echo "# $env-test.lock: generated by containers/aarch64/lock.sh from ../$env-test.in with -c $env.lock, minus $env.lock's packages"
    echo "# target: linux/aarch64 (manylinux_2_28), CPython 3.13; exclude-newer $CUTOFF"
    "$PY" "$IN/locktool.py" minus "$env-test.full" "$env.lock"; } > "$env-test.lock" && rm "$env-test.full"
done
# Packages with no wheel for CPython 3.13 on linux/aarch64 (locktool's x86_64 test, with the platform swapped).
"$PY" - "$IN" <<'PY' > lerobot.sdists
import inspect, sys
sys.path.insert(0, sys.argv[1])
import locktool as L
exec(inspect.getsource(L.has_wheel).replace('"x86_64" in plat', '"aarch64" in plat'), L.__dict__)
print("\n".join(L.sdist_only(open("lerobot.lock").read())))
PY
