#!/usr/bin/env bash
# Resolve the container lockfiles for the VM (linux/x86_64, CPython 3.13 as the reference notebook, amendment 30),
# with hashes, from any machine with uv (SPEC §15, amendment 28). The cutoff matches the date the local
# environments were installed with (pip --uploaded-prior-to), so unpinned dependencies are not newer.
# PyPI only: its torch 2.11.0 Linux wheel is the CUDA 13.0 build (see lerobot.in).
set -euo pipefail
cd "$(dirname "$0")"
UV="${UV:-uv}"
CUTOFF="2026-11-07T00:00:00Z"
for env in lerobot xvla build; do
  "$UV" pip compile "$env.in" -o "$env.lock" --generate-hashes --emit-index-url \
    --python-version 3.13 --python-platform x86_64-manylinux_2_28 \
    --index-url https://pypi.org/simple \
    --exclude-newer "$CUTOFF" --no-header --quiet
  { echo "# $env.lock: generated by containers/lock.sh from $env.in (uv $("$UV" --version | awk '{print $2}'))"
    echo "# target: linux/x86_64 (manylinux_2_28), CPython 3.13; exclude-newer $CUTOFF"
    cat "$env.lock"; } > "$env.lock.tmp" && mv "$env.lock.tmp" "$env.lock"
done
# Packages with no wheel for CPython 3.13 on linux/x86_64: the image builds them from their hashed sdists.
"${PY:-python3}" locktool.py sdists lerobot.lock > lerobot.sdists
"${PY:-python3}" locktool.py sdists xvla.lock > xvla.sdists
"${PY:-python3}" locktool.py sdists build.lock > build.sdists
